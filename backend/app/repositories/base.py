"""Async persistence boundary; transaction contexts own sessions and rollback."""
from contextlib import AbstractAsyncContextManager
from typing import Protocol
from uuid import uuid4
from app.domain.models import ActivityEvent, Dispatch, EmergencyUnit, Incident


def new_id(prefix: str) -> str:
    return f'{prefix}-{uuid4().hex[:12]}'


class Repository(Protocol):
    def transaction(self, *, write: bool = False) -> AbstractAsyncContextManager: ...
    async def event_cursor(self) -> tuple[str, int] | None: ...
    async def save_cursor(self, stream_id: str, sequence: int) -> None: ...
    async def persist_events(self, events: list) -> None: ...
    async def open(self) -> None: ...
    async def close(self) -> None: ...
    async def incident(self, identifier: str) -> Incident: ...
    async def unit(self, identifier: str) -> EmergencyUnit: ...
    async def dispatch(self, identifier: str) -> Dispatch: ...
    async def save_incident(self, value: Incident) -> None: ...
    async def save_unit(self, value: EmergencyUnit) -> None: ...
    async def save_dispatch(self, value: Dispatch) -> None: ...
    async def arrived_dispatch(self, incident_id: str) -> Dispatch | None: ...
    async def add_activity(self, value: ActivityEvent) -> None: ...
    async def snapshot(self) -> dict: ...
    async def reset(self) -> None: ...
    async def nearby_units(self, incident_id: str, radius: float, limit: int) -> list[dict]: ...
